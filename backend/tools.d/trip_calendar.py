"""trip_calendar — generate a shareable trip-calendar CMS page family.

Thin wrapper over chaba's scripts/ada/trip-calendar.py: shells the
generator with this lane's binding (collection/calendar resolved from
ADA_CMS_COLLECTION — the tool can never write another lane's CMS, same
construction as conv_journal) and returns the rollup link + leaf count
so she can answer "show my trip calendar" with a real URL.

The family follows docs/kb/cms-page-standard.md: rollup trip-<slug>
(mermaid gantt + day table), daily leaves trip-<slug>-<YYYY-MM-DD>, and
a trip-<slug>-qc coverage page; reports-index is regenerated by the
generator itself.

public='yes' flags the rollup+leaves meta.public → cms-publish-site.py
ships them to surf-thailand.com/<tenant>/. Gated like cms_publish_page:
public requires confirmed=true after an explicit user ask for a
public/shareable link.

LINE/TG share path: answer with public_url (or view_url on-tailnet);
page_snapshot renders the page to a PNG when the room prefers a picture.

Env:
    CHABA_REPO          chaba checkout holding scripts/ada/trip-calendar.py
                        (default ~/CascadeProjects/chaba)
    TRIP_CALENDAR       explicit generator path override
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path
from typing import Any

from backend.tool_runner.common import CMS_COLLECTION

DECLARATION = {
    "name": "trip_calendar",
    "description": (
        "Generate a trip-calendar page family (rollup + daily leaf pages) "
        "and return the link — use for 'show my trip calendar'."
    ),
    "parameters": {
        "type": "object",
        "properties": {
            "slug": {
                "type": "string",
                "description": "trip slug, e.g. 'capetown' — pages are "
                               "trip-<slug>[...]",
            },
            "start": {
                "type": "string",
                "description": "YYYY-MM-DD trip start — optional, "
                               "inferred from a matching calendar event.",
            },
            "end": {
                "type": "string",
                "description": "YYYY-MM-DD trip end — optional.",
            },
            "title": {
                "type": "string",
                "description": "display title override.",
            },
            "keywords": {
                "type": "string",
                "description": "comma-sep journal context match terms "
                               "(default: slug words).",
            },
            "public": {
                "type": "string",
                "description": "'yes' publishes to the lane's public "
                               "surf-thailand.com site — only when the "
                               "user explicitly asked for a shareable "
                               "link, and then pass confirmed='yes'.",
            },
            "confirmed": {
                "type": "string",
                "description": "'yes' only after the user confirmed "
                               "public publishing out loud.",
            },
        },
    },
}

_TRUE = {"yes", "true", "1", "on", "y"}


def _lane() -> str:
    """Lane binding by construction — ada-cms-pages[-<x>] -> tony|<x>."""
    if CMS_COLLECTION == "ada-cms-pages":
        return "tony"
    if CMS_COLLECTION.startswith("ada-cms-pages-"):
        return CMS_COLLECTION[len("ada-cms-pages-"):]
    return CMS_COLLECTION or "tony"


def _script() -> Path:
    override = os.environ.get("TRIP_CALENDAR", "").strip()
    if override:
        return Path(os.path.expanduser(override))
    repo = Path(os.path.expanduser(
        os.environ.get("CHABA_REPO", "~/CascadeProjects/chaba")))
    return repo / "scripts" / "ada" / "trip-calendar.py"


async def run(runner, **args) -> dict[str, Any]:
    slug = str(args.get("slug") or "").strip()
    if not slug:
        return {"ok": False, "error": "slug is required — e.g. "
                "trip_calendar(slug='capetown')"}
    public = str(args.get("public") or "").strip().lower() in _TRUE
    confirmed = str(args.get("confirmed") or "").strip().lower() in _TRUE
    if public and not confirmed:
        return {
            "ok": False,
            "error": ("public='yes' posts the rollup publicly to "
                      "boards.surf-thailand.com — re-call with "
                      "confirmed='yes' "
                      "only after the user explicitly asked for a "
                      "shareable public link"),
        }
    script = _script()
    if not script.is_file():
        return {"ok": False,
                "error": f"generator not found at {script} — set "
                         "CHABA_REPO or TRIP_CALENDAR"}
    cmd = [sys.executable, str(script), "--slug", slug,
           "--lane", _lane(), "--json"]
    for arg, flag in (("start", "--from"), ("end", "--to"),
                      ("title", "--title"), ("keywords", "--keywords")):
        v = str(args.get(arg) or "").strip()
        if v:
            cmd += [flag, v]
    if public:
        cmd.append("--public")
    try:
        proc = await asyncio.create_subprocess_exec(
            *cmd, stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE)
        out, err = await asyncio.wait_for(proc.communicate(), timeout=110)
    except asyncio.TimeoutError:
        return {"ok": False, "error": "generator timed out after 110s"}
    stdout = out.decode(errors="replace").strip()
    try:
        result = json.loads(stdout.splitlines()[-1])
    except Exception:
        return {"ok": False,
                "error": f"generator failed (rc={proc.returncode}): "
                         f"{(err.decode(errors='replace') or stdout)[-400:]}"}
    if proc.returncode != 0 or not result.get("ok"):
        return {"ok": False,
                "error": f"generator failed: "
                         f"{(err.decode(errors='replace') or stdout)[-400:]}"}
    result["note"] = (
        "Answer with the link — public_url is already live on "
        "boards.surf-thailand.com for LINE/TG sharing; view_url is "
        "the tailnet CMS copy. page_snapshot can render either to "
        "a PNG for image-send.")
    return result
